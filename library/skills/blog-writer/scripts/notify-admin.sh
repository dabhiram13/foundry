#!/bin/bash
# Send draft notification email to admin via Resend API
# Usage: ./notify-admin.sh '<json>'
# Example: ./notify-admin.sh '{"title":"My Post","slug":"my-post","category":"Guide","target_query":"how to X","word_count":1800,"description":"About this post"}'
#
# Required: title, slug
# Optional: category, target_query, word_count, description

set -e

JSON_INPUT="$1"

if [ -z "$JSON_INPUT" ]; then
    echo "Usage: ./notify-admin.sh '<json>'"
    echo ""
    echo "Required: title, slug"
    echo "Optional: category, target_query, word_count, description"
    exit 1
fi

if ! echo "$JSON_INPUT" | jq empty 2>/dev/null; then
    echo "Error: Invalid JSON input" >&2
    exit 1
fi

# Load env
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
ENV_FILE="$PROJECT_ROOT/webapp/.env"

if [ ! -f "$ENV_FILE" ]; then
    echo "Error: $ENV_FILE not found" >&2
    exit 1
fi

while IFS= read -r line; do
    [[ "$line" =~ ^#.*$ || -z "$line" ]] && continue
    line="${line#export }"
    [[ "$line" == *"="* ]] || continue
    export "$line" 2>/dev/null || true
done < "$ENV_FILE"

RESEND_KEY="${RESEND_API_KEY}"
ADMIN="${ADMIN_EMAIL}"
SITE_URL="${NEXT_PUBLIC_SITE_URL:-http://localhost:3000}"

if [ -z "$RESEND_KEY" ]; then
    echo "Warning: RESEND_API_KEY not set — skipping email notification" >&2
    echo '{"skipped": true, "reason": "RESEND_API_KEY not set"}'
    exit 0
fi

if [ -z "$ADMIN" ]; then
    echo "Warning: ADMIN_EMAIL not set — skipping email notification" >&2
    echo '{"skipped": true, "reason": "ADMIN_EMAIL not set"}'
    exit 0
fi

# Extract fields
TITLE=$(echo "$JSON_INPUT" | jq -r '.title')
SLUG=$(echo "$JSON_INPUT" | jq -r '.slug')
CATEGORY=$(echo "$JSON_INPUT" | jq -r '.category // "Uncategorized"')
TARGET_QUERY=$(echo "$JSON_INPUT" | jq -r '.target_query // "N/A"')
WORD_COUNT=$(echo "$JSON_INPUT" | jq -r '.word_count // "N/A"')
DESCRIPTION=$(echo "$JSON_INPUT" | jq -r '.description // ""')

PREVIEW_URL="${SITE_URL}/blog/${SLUG}"
ADMIN_URL="${SITE_URL}/protected/blog"

# Build HTML email
HTML_BODY="<div style=\"font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px;\">
<h1 style=\"font-size: 24px; margin-bottom: 8px;\">New Blog Draft Ready</h1>
<p style=\"color: #666; margin-top: 0;\">A new post has been drafted and is waiting for your review.</p>
<hr style=\"border: none; border-top: 1px solid #eee; margin: 20px 0;\">
<table style=\"width: 100%; border-collapse: collapse;\">
<tr><td style=\"padding: 8px 0; color: #666; width: 120px;\">Title</td><td style=\"padding: 8px 0; font-weight: 600;\">${TITLE}</td></tr>
<tr><td style=\"padding: 8px 0; color: #666;\">Category</td><td style=\"padding: 8px 0;\">${CATEGORY}</td></tr>
<tr><td style=\"padding: 8px 0; color: #666;\">AEO Target</td><td style=\"padding: 8px 0;\"><code>${TARGET_QUERY}</code></td></tr>
<tr><td style=\"padding: 8px 0; color: #666;\">Word Count</td><td style=\"padding: 8px 0;\">${WORD_COUNT}</td></tr>
</table>
<p style=\"color: #666; margin-top: 16px; font-size: 14px;\">${DESCRIPTION}</p>
<hr style=\"border: none; border-top: 1px solid #eee; margin: 20px 0;\">
<div style=\"text-align: center; margin: 24px 0;\">
<a href=\"${PREVIEW_URL}\" style=\"display: inline-block; padding: 12px 24px; background: #000; color: #fff; text-decoration: none; border-radius: 6px; font-weight: 500; margin-right: 8px;\">Preview Post</a>
<a href=\"${ADMIN_URL}\" style=\"display: inline-block; padding: 12px 24px; background: #fff; color: #000; text-decoration: none; border-radius: 6px; font-weight: 500; border: 1px solid #ddd;\">Open Dashboard</a>
</div>
<p style=\"color: #999; font-size: 12px; text-align: center;\">This draft was auto-generated by the blog-writer skill. Review and publish when ready.</p>
</div>"

# Send via Resend API
RESPONSE=$(curl -s -w "\n%{http_code}" \
    "https://api.resend.com/emails" \
    -H "Authorization: Bearer ${RESEND_KEY}" \
    -H "Content-Type: application/json" \
    -d "$(jq -n \
        --arg to "$ADMIN" \
        --arg subject "New Blog Draft: ${TITLE}" \
        --arg html "$HTML_BODY" \
        '{
            "from": "Blog Writer <onboarding@resend.dev>",
            "to": [$to],
            "subject": $subject,
            "html": $html
        }'
    )")

HTTP_CODE=$(echo "$RESPONSE" | tail -1)
BODY=$(echo "$RESPONSE" | sed '$d')

if [ "$HTTP_CODE" -ge 200 ] && [ "$HTTP_CODE" -lt 300 ]; then
    echo "$BODY" | jq '. + {"sent_to": "'"$ADMIN"'"}' 2>/dev/null || echo "$BODY"
else
    echo "Error sending email (HTTP $HTTP_CODE):" >&2
    echo "$BODY" >&2
    exit 1
fi
